import { describe, expect, it } from 'vitest';
import type { SubtitleCue } from '@migaku2/subtitles';
import {
  buildSummaryContextBlock,
  buildSummaryMessages,
  buildSummarySystemPrompt,
  measureTranscript,
  summaryContextFromCues,
} from '../src/lib/summary';
import { isExplainRequest, isSummaryRequest } from '../src/lib/messages';
import type { SummaryContext, SummaryRequest, VideoInfo } from '../src/lib/messages';

const info: VideoInfo = {
  site: 'youtube',
  title: 'Why do I keep forgetting words?',
  details: [
    { label: 'Channel', value: 'Learn' },
    { label: 'Description', value: '  ' },
  ],
  autoGenerated: false,
  language: 'en',
};

function subtitleCues(count: number, text = 'line'): SubtitleCue[] {
  return Array.from({ length: count }, (_, i) => ({
    start: i * 2_000,
    end: i * 2_000 + 1_500,
    text: `${text}${i}`,
  }));
}

function context(overrides: Partial<SummaryContext> = {}): SummaryContext {
  return { ...summaryContextFromCues(subtitleCues(50), info, false), ...overrides };
}

describe('measureTranscript', () => {
  it('counts dense scripts at about a token per character', () => {
    const ja = measureTranscript([{ text: 'あいうえお'.repeat(20), startMs: 0, endMs: 1 }]);
    const en = measureTranscript([{ text: 'abcde'.repeat(20), startMs: 0, endMs: 1 }]);
    expect(ja.tokens).toBeGreaterThan(en.tokens * 3);
  });

  it('reports how many cues fit the budget', () => {
    const cues = summaryContextFromCues(subtitleCues(100), info, false).cues;
    const size = measureTranscript(cues, 600);
    expect(size.fitCount).toBeGreaterThan(0);
    expect(size.fitCount).toBeLessThan(100);
    expect(measureTranscript(cues).fitCount).toBe(100);
  });
});

describe('summaryContextFromCues', () => {
  it('sends the whole transcript and drops empty details', () => {
    const c = summaryContextFromCues(subtitleCues(10), info, true);
    expect(c.cues).toHaveLength(10);
    expect(c.cutAtMs).toBeNull();
    expect(c.details).toEqual([{ label: 'Channel', value: 'Learn' }]);
  });

  it('cuts at the budget only when asked to', () => {
    const long = subtitleCues(30_000, 'x'.repeat(10));
    const cut = summaryContextFromCues(long, info, true);
    expect(cut.cues.length).toBeLessThan(long.length);
    expect(cut.cutAtMs).toBe(cut.cues.at(-1)!.endMs);
    expect(summaryContextFromCues(long, info, false).cues).toHaveLength(long.length);
  });
});

describe('summary prompt', () => {
  it('picks the prompt by transcript language', () => {
    expect(buildSummarySystemPrompt(context())).toContain('Write in English.');
    expect(buildSummarySystemPrompt(context({ language: 'en-US' }))).toContain('Write in English.');
    expect(buildSummarySystemPrompt(context({ language: 'ja' }))).toContain('日本語で書いてください。');
    const other = buildSummarySystemPrompt(context({ language: 'de' }));
    expect(other).toContain('Write in the same language as the transcript.');
    expect(buildSummarySystemPrompt(context({ language: '' }))).toBe(other);
  });

  it('tells the model about auto-generated or cut transcripts without asking it to say so', () => {
    const plain = buildSummarySystemPrompt(context());
    expect(plain).not.toContain('auto-generated');
    expect(plain).not.toContain('stops at');
    const asr = buildSummarySystemPrompt(context({ autoGenerated: true }));
    expect(asr).toContain('Do not mention transcription errors');
    const cut = buildSummarySystemPrompt(context({ cutAtMs: 9_000_000 }));
    expect(cut).toContain('stops at 2:30:00');
    expect(buildSummarySystemPrompt(context({ language: 'ja', cutAtMs: 9_000_000 }))).toContain('2:30:00までで切れて');
  });

  it('includes the whole transcript, marking a cut', () => {
    const block = buildSummaryContextBlock(context());
    expect(block).toContain('Title: Why do I keep forgetting words?');
    expect(block).toContain('<transcript language="en">');
    expect(block).toContain('[00:00] line0');
    expect(block).toContain('[01:38] line49');
    expect(block).not.toContain('cut here');
    expect(buildSummaryContextBlock(context({ cutAtMs: 1 }))).toContain('cut here for length');
  });

  it('caches the transcript and asks in the prompt language', () => {
    const request: SummaryRequest = {
      context: context({ language: 'ja' }),
      history: [{ question: '', answer: '要約' }],
      question: 'もっと詳しく',
    };
    const messages = buildSummaryMessages(request);
    expect(messages.map((m) => m.role)).toEqual(['system', 'user', 'assistant', 'user']);
    const first = messages[1]!.content;
    expect(Array.isArray(first) && first[0]!.cache_control).toEqual({ type: 'ephemeral' });
    expect(Array.isArray(first) && first[1]!.text).toBe('この動画を要約してください。');
    expect(messages[3]!.content).toBe('もっと詳しく');
  });
});

describe('summary request validation', () => {
  const request: SummaryRequest = { context: context(), history: [], question: '' };

  it('accepts summaries and keeps them apart from explain requests', () => {
    expect(isSummaryRequest(request)).toBe(true);
    expect(isSummaryRequest({ ...request, context: context({ cutAtMs: 5_000 }) })).toBe(true);
    expect(isSummaryRequest({ ...request, context: { ...context(), cutAtMs: undefined } })).toBe(false);
    expect(isSummaryRequest({ ...request, context: context({ cues: [] }) })).toBe(false);
    expect(isExplainRequest(request)).toBe(false);
  });
});
