import type { SubtitleCue } from '@migaku2/subtitles';
import {
  buildChatMessages,
  languageName,
  toTranscriptCues,
  transcriptLine,
  transcriptOpenTag,
  videoBlock,
  withoutEmptyDetails,
} from './assistant';
import type { ChatMessage } from './assistant';
import type { ExplainContext, ExplainRequest, TranscriptCue, VideoInfo } from './messages';

// Prompt building for explanations. Pure (no DOM, no network) so the sidebar
// sites and 4989 share one set of rules and it can be unit-tested.

/** Cues after the selection the model may see: enough to finish the scene,
 * not enough to spoil what comes later. */
export const LOOKAHEAD_CUES = 20;
/** Transcript budget in characters (Japanese is roughly a token per char).
 * Beyond it the earliest cues are dropped first. */
export const MAX_TRANSCRIPT_CHARS = 60_000;

/** Map sidebar cues and a selection to the context sent for explanation. */
export function explainContextFromCues(
  cues: SubtitleCue[],
  selection: { from: number; to: number; selectedText: string },
  info: VideoInfo,
): ExplainContext | null {
  if (selection.from < 0 || selection.to >= cues.length || selection.from > selection.to) return null;
  return {
    ...withoutEmptyDetails(info),
    cues: toTranscriptCues(cues),
    from: selection.from,
    to: selection.to,
    selectedText: selection.selectedText,
  };
}

export interface TranscriptWindow {
  /** Original indexes are kept so the selection can be marked. */
  cues: Array<{ cue: TranscriptCue; index: number }>;
  omittedBefore: boolean;
  omittedAfter: boolean;
}

/** Everything up to the selection plus a short lookahead, trimmed from the
 * start to fit the budget. The selection itself is never trimmed. */
export function transcriptWindow(
  context: ExplainContext,
  maxChars = MAX_TRANSCRIPT_CHARS,
  lookahead = LOOKAHEAD_CUES,
): TranscriptWindow {
  const last = Math.min(context.cues.length - 1, context.to + lookahead);
  let first = 0;
  let chars = 0;
  for (let i = last; i >= 0; i--) {
    chars += context.cues[i]!.text.length + 12;
    if (chars > maxChars && i < context.from) {
      first = i + 1;
      break;
    }
  }
  const cues: TranscriptWindow['cues'] = [];
  for (let i = first; i <= last; i++) cues.push({ cue: context.cues[i]!, index: i });
  return { cues, omittedBefore: first > 0, omittedAfter: last < context.cues.length - 1 };
}

export function buildSystemPrompt(context: ExplainContext, explainLanguage: string): string {
  const target = languageName(context.language);
  const parts: string[] = [];
  if (context.autoGenerated) {
    parts.push(
      'IMPORTANT: This transcript was auto-generated by speech recognition and may contain ' +
        'mis-transcriptions. If the selected text looks wrong, say what was probably said ' +
        'instead before explaining it.',
    );
  }
  parts.push(
    `You help a ${target} learner understand something they heard while watching a video. ` +
      'They selected part of the transcript and want to know why it is said the way it is: ' +
      'meaning, nuance, grammar, word choice, register, who is speaking to whom, cultural ' +
      'background, or what is going on in the scene — whatever their question is about.',
    'Ground the explanation in the transcript and the video details. Say when you are ' +
      'inferring something the transcript does not show (for example who is speaking).',
    'The transcript deliberately stops shortly after the selection. Do not speculate about ' +
      'or reveal what happens later in the story.',
    'Lead with the direct answer, then supporting detail. Keep it concise. Use short ' +
      'paragraphs, **bold** for key terms and lists where they help; no tables. Quote ' +
      `${target} as written, adding readings in parentheses for harder words.`,
    `Write in ${explainLanguage || 'English'}. If the learner writes their question in a ` +
      'different language, answer in that language instead.',
  );
  return parts.join('\n\n');
}

export function buildContextBlock(context: ExplainContext): string {
  const lines: string[] = [...videoBlock(context), ''];
  const window = transcriptWindow(context);
  lines.push(transcriptOpenTag(context));
  if (window.omittedBefore) lines.push('(earlier lines omitted)');
  for (const { cue, index } of window.cues) {
    lines.push(transcriptLine(cue, index >= context.from && index <= context.to ? '▶ ' : ''));
  }
  if (window.omittedAfter) lines.push('(transcript continues; not shown)');
  lines.push('</transcript>', '');
  lines.push('Lines marked ▶ contain the selection.');
  lines.push(`<selection>${context.selectedText.trim()}</selection>`);
  return lines.join('\n');
}

export function buildExplainMessages(request: ExplainRequest, explainLanguage: string): ChatMessage[] {
  return buildChatMessages(
    buildSystemPrompt(request.context, explainLanguage),
    buildContextBlock(request.context),
    request.history,
    request.question,
    'Explain the selected text.',
  );
}
