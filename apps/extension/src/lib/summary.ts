import type { SubtitleCue } from '@migaku2/subtitles';
import {
  baseLanguage,
  buildChatMessages,
  formatClock,
  toTranscriptCues,
  transcriptLine,
  transcriptOpenTag,
  videoBlock,
  withoutEmptyDetails,
} from './assistant';
import type { ChatMessage } from './assistant';
import type { SummaryContext, SummaryRequest, TranscriptCue, VideoInfo } from './messages';

// Prompt building for summaries. Unlike explanations the model sees the whole
// transcript, spoilers included. Pure so it can be unit-tested.

/** Transcript budget in characters before the learner is asked whether to
 * send everything. Counted like the explain budget (text plus timestamp). */
export const SUMMARY_MAX_CHARS = 250_000;

const LINE_OVERHEAD_CHARS = 12;
const LINE_OVERHEAD_TOKENS = 5;
/** Kana, kanji and hangul run about a token per character; most other
 * scripts about four characters per token. */
const DENSE_SCRIPT = /[぀-ヿ㐀-鿿豈-﫿가-힯]/g;

export interface TranscriptSize {
  chars: number;
  /** Rough input-token estimate for the transcript. */
  tokens: number;
  /** How many cues from the start fit in the budget. */
  fitCount: number;
}

export function measureTranscript(cues: TranscriptCue[], maxChars = SUMMARY_MAX_CHARS): TranscriptSize {
  let chars = 0;
  let tokens = 0;
  let fitCount = 0;
  for (const cue of cues) {
    chars += cue.text.length + LINE_OVERHEAD_CHARS;
    if (chars <= maxChars) fitCount++;
    const dense = cue.text.match(DENSE_SCRIPT)?.length ?? 0;
    tokens += dense + (cue.text.length - dense) / 4 + LINE_OVERHEAD_TOKENS;
  }
  return { chars, tokens: Math.round(tokens), fitCount };
}

/** The context sent for a summary; `cut` keeps only the start that fits the budget. */
export function summaryContextFromCues(cues: SubtitleCue[], info: VideoInfo, cut: boolean): SummaryContext {
  const all = toTranscriptCues(cues);
  const { fitCount } = measureTranscript(all);
  const kept = cut && fitCount < all.length ? all.slice(0, Math.max(1, fitCount)) : all;
  return {
    ...withoutEmptyDetails(info),
    cues: kept,
    cutAtMs: kept.length < all.length ? kept[kept.length - 1]!.endMs : null,
  };
}

type PromptLanguage = 'en' | 'ja' | 'other';

function promptLanguage(context: SummaryContext): PromptLanguage {
  const base = baseLanguage(context.language);
  return base === 'en' || base === 'ja' ? base : 'other';
}

export function buildSummarySystemPrompt(context: SummaryContext): string {
  const cut = context.cutAtMs !== null ? formatClock(context.cutAtMs) : null;
  if (promptLanguage(context) === 'ja') {
    const parts = ['あなたは動画の内容を要約します。動画の情報と書き起こしが与えられます。'];
    if (context.autoGenerated) {
      parts.push(
        'この書き起こしは音声認識による自動生成のため、誤認識が含まれている可能性があります。' +
          '文脈から本来の発言を推測してください。誤認識については回答の中で触れないでください。',
      );
    }
    if (cut) {
      parts.push(
        `動画が長いため、書き起こしは${cut}までで切れていて、それ以降は含まれていません。` +
          'ユーザーはこのことを承知しているので、回答の中で触れないでください。',
      );
    }
    parts.push(
      [
        '要約の書き方:',
        '- 最初の一文で要点を述べてください。タイトルが問いかけになっている場合や、学びや教訓を予告している場合（例:「この習慣で英語力が変わった」）は、その一文で直接答えてください。',
        '- 続けて、重要な内容を短い箇条書き3〜6個で。箇条書きが合わない場合は、ごく短い段落1〜2つで。',
        '- 全体で400字程度まで。1分以内で読める長さにしてください。',
        '- 前置き（「この動画では〜」など）、締めのまとめ、余計な言葉は不要です。',
        '- Markdownを使い、**太字**は控えめに。見出しや表は使わないでください。',
        '- 日本語で書いてください。',
      ].join('\n'),
      '要約の後、ユーザーが動画について追加で質問することがあります。書き起こしに基づいて簡潔に答えてください。',
    );
    return parts.join('\n\n');
  }

  const other = promptLanguage(context) === 'other';
  const parts = ['You summarize a video. You get the video details and its transcript.'];
  if (context.autoGenerated) {
    parts.push(
      'The transcript was auto-generated by speech recognition and may contain ' +
        'mis-transcriptions. Infer what was meant from context. Do not mention transcription ' +
        'errors in your answer.',
    );
  }
  if (cut) {
    parts.push(
      `The video is long, so the transcript stops at ${cut}; the rest is not included. The ` +
        'reader already knows this, so do not mention it in your answer.',
    );
  }
  parts.push(
    [
      'How to write the summary:',
      '- Open with one sentence that states the main point. If the title asks a question or ' +
        'promises a lesson or takeaway (for example "This one habit changed how I learn"), that ' +
        'sentence answers it directly.',
      '- Then 3–6 short bullet points with the most important content, or 1–2 very short ' +
        'paragraphs if bullets do not fit.',
      other
        ? '- At most about 150 words, or the equivalent length in the language you write in. It ' +
          'should take under a minute to read.'
        : '- At most about 150 words. It should take under a minute to read.',
      '- No introduction ("This video is about…"), no closing recap, no filler.',
      '- Use markdown, with **bold** sparingly. No headings or tables.',
      other ? '- Write in the same language as the transcript.' : '- Write in English.',
    ].join('\n'),
    'After the summary, the reader may ask follow-up questions about the video. Answer them ' +
      'concisely, grounded in the transcript.',
  );
  return parts.join('\n\n');
}

export function buildSummaryContextBlock(context: SummaryContext): string {
  const lines: string[] = [...videoBlock(context), '', transcriptOpenTag(context)];
  for (const cue of context.cues) lines.push(transcriptLine(cue));
  if (context.cutAtMs !== null) lines.push('(transcript cut here for length; the rest is not included)');
  lines.push('</transcript>');
  return lines.join('\n');
}

export function buildSummaryMessages(request: SummaryRequest): ChatMessage[] {
  return buildChatMessages(
    buildSummarySystemPrompt(request.context),
    buildSummaryContextBlock(request.context),
    request.history,
    request.question,
    promptLanguage(request.context) === 'ja' ? 'この動画を要約してください。' : 'Summarize the video.',
  );
}
