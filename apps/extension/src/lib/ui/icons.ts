export type IconName = keyof typeof PATHS;

const SVG_NS = 'http://www.w3.org/2000/svg';

// Built node by node: YouTube enforces Trusted Types, so no innerHTML.
export function icon(name: IconName, className = ''): SVGSVGElement {
  const svg = document.createElementNS(SVG_NS, 'svg');
  const attrs: Record<string, string> = {
    viewBox: '0 0 24 24',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': '2',
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round',
    'aria-hidden': 'true',
    class: `m2-icon ${className}`.trim(),
  };
  for (const [k, v] of Object.entries(attrs)) svg.setAttribute(k, v);
  for (const [, tag, body] of PATHS[name].matchAll(/<(\w+) ([^>]*)\/>/g)) {
    const child = document.createElementNS(SVG_NS, tag!);
    for (const [, k, v] of body!.matchAll(/([\w-]+)="([^"]*)"/g)) child.setAttribute(k!, v!);
    svg.append(child);
  }
  return svg;
}

/** Replace a button's content with an icon and optional text label. */
export function setButtonContent(el: HTMLElement, name: IconName | null, label = ''): void {
  el.replaceChildren(...(name ? [icon(name, name === 'loader' ? 'm2-spin' : '')] : []));
  if (label) el.append(label);
}
